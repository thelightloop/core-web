function daysBetween(a: Date, b: Date): number {
  const msPerDay = 86400000
  const utcA = Date.UTC(a.getFullYear(), a.getMonth(), a.getDate())
  const utcB = Date.UTC(b.getFullYear(), b.getMonth(), b.getDate())
  return Math.floor((utcB - utcA) / msPerDay)
}

export function adToBs(adDateStr: string): string {
  if (!adDateStr) return ''
  const adDate = new Date(adDateStr)
  if (isNaN(adDate.getTime())) return ''

  const refDate = new Date(AD_REF.year, AD_REF.month, AD_REF.day)
  let totalDays = daysBetween(refDate, adDate)
  if (totalDays < 0) return ''

  let bsYear = BS_START_YEAR
  let bsMonth = 0 // 0-indexed
  let bsDay = 1

  // Walk through BS years
  while (bsYear - BS_START_YEAR < BS_MONTH_DATA.length) {
    const yearData = BS_MONTH_DATA[bsYear - BS_START_YEAR]
    const daysInYear = yearData.reduce((a, b) => a + b, 0)
    if (totalDays < daysInYear) break
    totalDays -= daysInYear
    bsYear++
  }

  if (bsYear - BS_START_YEAR >= BS_MONTH_DATA.length) return ''

  // Walk through BS months
  const monthData = BS_MONTH_DATA[bsYear - BS_START_YEAR]
  for (let m = 0; m < 12; m++) {
    if (totalDays < monthData[m]) {
      bsMonth = m
      bsDay = totalDays + 1
      break
    }
    totalDays -= monthData[m]
  }

  const mm = String(bsMonth + 1).padStart(2, '0')
  const dd = String(bsDay).padStart(2, '0')
  return `${bsYear}/${mm}/${dd}`
}
